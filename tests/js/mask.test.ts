import { describe, expect, it } from 'vitest';
import { applyMask } from '../../resources/js/core/mask';

describe('applyMask', () => {
    it.each([
        ['12252026', '99/99/9999', '12/25/2026'],
        ['12/25/2026', '99/99/9999', '12/25/2026'],
        ['12', '99/99/9999', '12'],
        ['123', '99/99/9999', '12/3'],
        ['12/', '99/99/9999', '12/'],
        ['', '99/99/9999', ''],
        ['12x34', '99/99', '12/34'],
        ['abc', '999', ''],
        ['ab12', 'aa-99', 'ab-12'],
        ['a1b2', '**-**', 'a1-b2'],
        ['123456789', '999', '123'],
        ['6175551234', '(999) 999-9999', '(617) 555-1234'],
    ])('fits %s to %s', (value, mask, expected) => {
        expect(applyMask(value, mask)).toBe(expected);
    });
});
